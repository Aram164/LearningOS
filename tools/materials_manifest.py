#!/usr/bin/env python3
"""Checksummed inventory of the external materials tree.

    python tools/materials_manifest.py                         # verify live tree (size + presence)
    python tools/materials_manifest.py --deep                  # verify live tree (sha256)
    python tools/materials_manifest.py --against PATH          # verify a restored copy (sha256)
    python tools/materials_manifest.py --against PATH --fast   # size + presence only

WHY THIS EXISTS
---------------
``materials/`` lives outside the authored tree by design (CLAUDE.md §11) and is
tracked by no Git repository — it is ~1.9 GB of PDFs, slides and notebooks.
Hundreds of ``material://`` references in canonical records resolve into it.
Before this manifest the repository had no record of what *should* be there, so
it could not tell the difference between three very different situations:

    the drive is unmounted        (recoverable, ignore)
    a file was deliberately moved (update the inventory)
    a file is silently gone       (data loss — the reference is now a lie)

The manifest is the repository's own durable record of the external tree, so
those cases become distinguishable and a restored backup can be *proved*
complete and uncorrupted with ``--against``, which compares recorded checksums.
``--fast`` answers the weaker question (size + presence only) deliberately.

WHAT IS EXCLUDED
----------------
Symlinks (the ``.flat/`` URI-compat farm points back into the same tree),
``.DS_Store``, the three artifacts ``tools/build_materials_index.py``
regenerates (``README.md``, ``FILES.txt``, ``INDEX.html``), and the per-folder
``SOURCES.md`` files ``tools/build_materials_tree.py`` rewrites — derived data
is reproducible and would drift the manifest on every ``make materials``.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import os
import sys
from pathlib import Path

import yaml

from learning_os.domain.material_inventory import (
    render_manifest as render_manifest,  # public re-export
)

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "records" / "materials-manifest.yaml"
SCHEMA_VERSION = 1
# Byte ordering and wrap width are shared with preserved planners through
# learning_os.domain.material_inventory; this entrypoint owns inventory I/O only.

#: Regenerated by tools/build_materials_index.py — derived, not durable.
GENERATED_AT_ROOT = frozenset({"README.md", "FILES.txt", "INDEX.html"})
#: Regenerated per folder by tools/build_materials_tree.py at any depth, so the
#: manifest would otherwise drift on every `make materials`.
GENERATED_ANYWHERE = frozenset({"SOURCES.md"})
SKIP_NAMES = frozenset({".DS_Store"})


def _iter_non_symlink_files(base: Path):
    """Yield sorted regular non-symlink files under ``base`` (Python 3.12+ safe)."""
    for dirpath, dirnames, filenames in os.walk(base, followlinks=False):
        current = Path(dirpath)
        dirnames[:] = sorted(name for name in dirnames if not (current / name).is_symlink())
        for name in sorted(filenames):
            candidate = current / name
            if not candidate.is_symlink() and candidate.is_file():
                yield candidate


def materials_root(root: Path = ROOT) -> Path:
    """``materials/`` sits beside the repository, under the LearningOS root."""
    return root.parent / "materials"


def iter_material_files(base: Path):
    """Yield (relative_posix_path, absolute_path) for every durable file."""
    if base.is_symlink() or not base.is_dir():
        return
    for path in _iter_non_symlink_files(base):
        if path.name in SKIP_NAMES or path.name in GENERATED_ANYWHERE:
            continue
        rel = path.relative_to(base)
        if len(rel.parts) == 1 and rel.name in GENERATED_AT_ROOT:
            continue
        yield rel.as_posix(), path


def sha256(path: Path, chunk: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(chunk):
            digest.update(block)
    return digest.hexdigest()


def build(base: Path) -> dict:
    files: dict[str, dict] = {}
    total = 0
    for rel, path in iter_material_files(base):
        size = path.stat().st_size
        files[rel] = {"size": size, "sha256": sha256(path)}
        total += size
    return {
        "schema_version": SCHEMA_VERSION,
        "captured": _dt.date.today().isoformat(),
        "totals": {"files": len(files), "bytes": total},
        "files": files,
    }


def _manifest_label() -> str:
    """How to name the manifest in a message, wherever it happens to live.

    `relative_to` raises when the manifest is not under ROOT, which turns a
    print into a traceback. That never happens in normal use — the constant
    points inside the repository — but it made every test that redirects the
    manifest depend on the temporary directory happening to sit inside the
    checkout, which is a property of the machine, not of the code.
    """
    try:
        return str(MANIFEST.relative_to(ROOT))
    except ValueError:
        return str(MANIFEST)


def load_manifest(path: Path = MANIFEST) -> dict | None:
    if not path.exists():
        return None
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def verify(manifest: dict, base: Path, deep: bool = False) -> dict:
    """Compare a materials tree against the manifest.

    Returns {missing, changed, unregistered, unverifiable} — all sorted lists of paths.
    ``changed`` compares size always, and sha256 additionally when *deep*.
    ``unverifiable`` tracks paths lacking a recorded sha256 when *deep* is requested.
    """
    recorded = manifest.get("files") or {}
    present = dict(iter_material_files(base))

    missing = sorted(set(recorded) - set(present))
    unregistered = sorted(set(present) - set(recorded))
    changed = []
    unverifiable = []
    for rel in sorted(set(recorded) & set(present)):
        want, path = recorded[rel], present[rel]
        if path.stat().st_size != want.get("size"):
            changed.append(rel)
        elif deep:
            want_sha256 = want.get("sha256")
            if not isinstance(want_sha256, str):
                unverifiable.append(rel)
            elif sha256(path) != want_sha256:
                changed.append(rel)
    return {"missing": missing, "changed": changed, "unregistered": unregistered, "unverifiable": unverifiable}


def _report(result: dict, base: Path, deep: bool) -> int:
    tiers = (("missing", "recorded but NOT PRESENT"),
             ("changed", "content differs from the manifest"),
             ("unverifiable", "have no recorded checksums (content could not be checked)"),
             ("unregistered", "present but not in the manifest"))
    worst = 0
    for key, blurb in tiers:
        rows = result[key]
        if not rows:
            continue
        worst = max(worst, 1 if key != "unregistered" else 0)
        print(f"\n{len(rows)} file(s) {blurb}:")
        for rel in rows[:20]:
            print(f"  {rel}")
        if len(rows) > 20:
            print(f"  … and {len(rows) - 20} more")

    # The summary has to agree with the exit code. An unregistered file is a
    # report and not a failure, so a run that found only those still succeeded
    # and must not print FAIL at someone reading the log rather than `$?`.
    depth = " (sha256 verified)" if deep else " (size + presence)"
    if worst:
        print(f"FAIL — {base} does not match the manifest{depth}")
    elif result["unregistered"]:
        print(f"OK — {base} holds everything the manifest records{depth}; "
              f"the {len(result['unregistered'])} unregistered file(s) above are not a failure")
    else:
        print(f"OK — {base} matches the manifest{depth}")
    return worst


def build_parser() -> argparse.ArgumentParser:
    """The tool's CLI surface (SPEC §7.4, PLAN D11)."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", action="store_true",
                        help="rebuild the manifest from the current tree")
    parser.add_argument("--deep", action="store_true",
                        help="verify sha256 of every file, not just size")
    parser.add_argument("--fast", action="store_true",
                        help="verify size and presence only")
    parser.add_argument("--against", default=None, metavar="PATH",
                        help="verify a restored copy at PATH instead of the live tree (hashes by default)")
    return parser


class _ManifestSyncRefused(RuntimeError):
    """Raised when ``--build`` cannot dispatch through the admitted gateway."""


def _commit_manifest_via_gateway(base: Path, *, manifest_path: Path | None = None) -> dict:
    """Collect the manifest from ``base`` and commit via GatewayEnvelopeV2.

    ``materials_manifest.py`` contains no direct write primitives; persistence
    runs exclusively through ``materials.manifest.sync`` -> ``TransactionService``.
    """
    raw_target = manifest_path or MANIFEST
    raw_abs = Path(os.path.abspath(raw_target))
    if len(raw_abs.parents) < 2 or raw_abs.parent.name != "records" or raw_abs.name != "materials-manifest.yaml":
        raise _ManifestSyncRefused(
            f"manifest target must be <repo>/records/materials-manifest.yaml, got {raw_abs}"
        )
    for candidate in (raw_abs, raw_abs.parent, raw_abs.parents[1]):
        if candidate.is_symlink():
            raise _ManifestSyncRefused(f"refusing symlink manifest target: {candidate}")
    raw_repo_root = raw_abs.parents[1]
    if not (raw_repo_root / "system" / "contracts" / "capabilities.yaml").is_file():
        raise _ManifestSyncRefused(
            f"cannot commit manifest outside an initialized LearningOS repository ({raw_repo_root})"
        )
    repo_root = raw_repo_root.resolve()
    target = raw_abs.resolve()
    if target != repo_root / "records" / "materials-manifest.yaml":
        raise _ManifestSyncRefused(f"refusing symlink manifest target: {raw_abs}")

    try:
        import uuid

        from learning_os.app.lock import operator_lock
        from learning_os.app.pipeline import close_attempt, run_gateway
        from learning_os.domain.failures import WriteRefused
        from learning_os.store.contracts.capability_catalog import command_definitions
        from learning_os.store.contracts.gateway import intent_sha256
        from learning_os.store.diagnostics import tracer as diag_tracer
        from learning_os.store.diagnostics.store import bind_store as _bind_diag_store
        from learning_os.store.fingerprint import snapshot as _snapshot
        from learning_os.store.revisions import artifact_revision
    except ModuleNotFoundError as exc:
        raise _ManifestSyncRefused(
            f"materials.manifest.sync gateway runtime is unavailable ({exc.name})"
        ) from exc

    definitions = command_definitions(repo_root)
    if "materials.manifest.sync" not in definitions:
        raise _ManifestSyncRefused(
            "capabilities catalog does not declare materials.manifest.sync"
        )

    _bind_diag_store(repo_root)
    attempt = diag_tracer.begin_attempt({"capability": "materials.manifest.sync"})
    try:
        with operator_lock(repo_root):
            manifest = build(base)
            expected_snapshot = _snapshot(repo_root)
            artifact = "file:records/materials-manifest.yaml"
            expected_revisions = {artifact: artifact_revision(repo_root, artifact)}
            envelope = {
                "schema_version": 2,
                "request_id": f"manifest-sync-{uuid.uuid4().hex}",
                "idempotency_key": f"manifest-sync-{uuid.uuid4().hex}",
                "capability": "materials.manifest.sync",
                "channel": "operator",
                "expected_snapshot": expected_snapshot,
                "expected_revisions": expected_revisions,
                "approval": {
                    "kind": "operator-approval",
                    "subject_sha256": "sha256:" + "0" * 64,
                },
                "payload": {
                    "record": manifest,
                },
            }
            envelope["approval"]["subject_sha256"] = intent_sha256(envelope)
            outcome = run_gateway(
                repo_root,
                envelope,
                requested="materials.manifest.sync",
                definitions=definitions,
                attempt=attempt,
                replay_only=False,
            )
    except WriteRefused as exc:
        close_attempt(attempt, 2, "error", {"stage": "core.admission"})
        raise _ManifestSyncRefused(str(exc)) from exc
    except Exception:
        close_attempt(attempt, 1, "error", {"stage": "core.materials_manifest"})
        raise

    if outcome.exit_code != 0:
        detail = outcome.stderr.strip() or outcome.stdout.strip() or f"exit {outcome.exit_code}"
        raise _ManifestSyncRefused(detail)
    return manifest


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    if args.deep and args.fast:
        print("cannot specify both --deep and --fast", file=sys.stderr)
        return 2

    if args.deep:
        resolved_deep = True
    elif args.fast:
        resolved_deep = False
    else:
        resolved_deep = bool(args.against)

    base = Path(args.against).resolve() if args.against else materials_root()

    if args.build:
        if not base.is_dir():
            print(f"materials tree not found: {base}", file=sys.stderr)
            return 2
        try:
            manifest = _commit_manifest_via_gateway(base)
        except _ManifestSyncRefused as exc:
            print(f"refused: {exc}", file=sys.stderr)
            return 2
        gb = manifest["totals"]["bytes"] / 1024**3
        print(f"wrote {_manifest_label()}: "
              f"{manifest['totals']['files']} files, {gb:.2f} GB")
        return 0

    manifest = load_manifest()
    if manifest is None:
        print(f"no manifest at {_manifest_label()} — "
              "run with --build first", file=sys.stderr)
        return 2
    if not base.is_dir():
        print(f"materials tree not found: {base}\n"
              "Nothing was checked. If the drive is simply unmounted this is "
              "not data loss; the manifest still records what belongs there.",
              file=sys.stderr)
        return 2

    print(f"manifest captured {manifest.get('captured')} — "
          f"{manifest.get('totals', {}).get('files')} files")
    return _report(verify(manifest, base, deep=resolved_deep), base, resolved_deep)


if __name__ == "__main__":
    raise SystemExit(main())
