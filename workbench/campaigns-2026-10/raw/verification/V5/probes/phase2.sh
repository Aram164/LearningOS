#!/bin/bash
# V5 phase 2: the documented drill on a full copy of the V5 clone.
# Clone state: Core fb73b0f9 (clean), UI f7dbc1f7 (clean), no materials in git,
# so the materials authority is an empty directory (the machine's true state).
set -u
export TMPDIR="$HOME/los-glm-V5-2026-10/tmp"
export HOMEROOT="$HOME/los-glm-V5-2026-10"
LOS="$HOMEROOT/repository/.venv/bin/python $HOMEROOT/repository/tools/los.py"

mark() { echo; echo "===== $1 ====="; }

mark "empty materials authority (true clone state)"
mkdir -p "$HOMEROOT/materials"
ls -la "$HOMEROOT/materials"

mark "UI shippable: plugin/build-info.json generated by npm run build (WORKFLOWS §31)"
ls "$HOMEROOT/obsidian-ui/plugin/build-info.json"
git -C "$HOMEROOT/obsidian-ui" status --porcelain | wc -l

mark "clone still clean before backup"
git -C "$HOMEROOT/repository" status --porcelain | wc -l
git -C "$HOMEROOT/obsidian-ui" status --porcelain | wc -l

mark "1. BACK UP: manifest the clone's three roots outside every root"
cd "$HOMEROOT/repository"
$LOS backup-manifest --out "$HOMEROOT/scratch/manifest.json" > "$HOMEROOT/scratch/summary.json"
echo "exit=$?"
cat "$HOMEROOT/scratch/summary.json" | $HOMEROOT/repository/.venv/bin/python -c 'import json,sys; d = json.load(sys.stdin); print("ok:", d["ok"]); print("roots:", d["roots"]); print("entries:", d["entries"]); print("aggregate:", d["aggregate_sha256"])'

mark "manifest provenance (commit pairing)"
$HOMEROOT/repository/.venv/bin/python -c 'import json; d = json.load(open("'"$HOMEROOT"'/scratch/manifest.json")); print("core:", d["provenance"]["core"]); print("ui:", d["provenance"]["ui"]); print("data_contract_version:", d["provenance"]["data_contract_version"]); print("materials_aliases:", d["materials_aliases"]); import collections; print("entries per root:", dict(collections.Counter(e["root"] for e in d["entries"])))'

mark "2+3. RESTORE into empty scratch/restore-1 (cp -a each authority)"
rm -rf "$HOMEROOT/scratch/restore-1"
mkdir -p "$HOMEROOT/scratch/restore-1"
cp -a "$HOMEROOT/repository" "$HOMEROOT/scratch/restore-1/repository"
cp -a "$HOMEROOT/obsidian-ui" "$HOMEROOT/scratch/restore-1/obsidian-ui"
cp -a "$HOMEROOT/materials" "$HOMEROOT/scratch/restore-1/materials"
echo "restored:"; ls "$HOMEROOT/scratch/restore-1"

mark "4. DIFF the trees (excluding only contract-declared excluded names)"
EX="-x .DS_Store -x .git -x .flat -x node_modules -x generated -x dist -x coverage"
diff -r -q $EX "$HOMEROOT/repository" "$HOMEROOT/scratch/restore-1/repository" && echo "core: copies match"
diff -r -q $EX "$HOMEROOT/obsidian-ui" "$HOMEROOT/scratch/restore-1/obsidian-ui" && echo "ui: copies match"
diff -r -q $EX "$HOMEROOT/materials" "$HOMEROOT/scratch/restore-1/materials" && echo "materials: copies match"

mark "5a. VERIFY checksums-only on the restore"
$LOS backup-verify --manifest "$HOMEROOT/scratch/manifest.json" \
  --restored-core "$HOMEROOT/scratch/restore-1/repository" \
  --restored-ui "$HOMEROOT/scratch/restore-1/obsidian-ui" \
  --restored-materials "$HOMEROOT/scratch/restore-1/materials" \
  --checksums-only > "$HOMEROOT/scratch/verify-checksums.json"; echo "exit=$?"; head -c 600 "$HOMEROOT/scratch/verify-checksums.json"; echo

mark "5b. VERIFY in full on the restore"
$LOS backup-verify --manifest "$HOMEROOT/scratch/manifest.json" \
  --restored-core "$HOMEROOT/scratch/restore-1/repository" \
  --restored-ui "$HOMEROOT/scratch/restore-1/obsidian-ui" \
  --restored-materials "$HOMEROOT/scratch/restore-1/materials" \
  > "$HOMEROOT/scratch/verify-full.json"; echo "exit=$?"
$HOMEROOT/repository/.venv/bin/python -c 'import json; d = json.load(open("'"$HOMEROOT"'/scratch/verify-full.json")); print("ok:", d["ok"]); [print(c["id"], c["ok"], "" if c["ok"] else json.dumps(c.get("detail", {}))[:400]) for c in d["checks"]]'

mark "OBSERVATION: same verify with materials UNMOUNTED (no restore-1/materials)"
$LOS backup-verify --manifest "$HOMEROOT/scratch/manifest.json" \
  --restored-core "$HOMEROOT/scratch/restore-1/repository" \
  --restored-ui "$HOMEROOT/scratch/restore-1/obsidian-ui" \
  --restored-materials "$HOMEROOT/scratch/restore-1/nonexistent-materials" \
  > "$HOMEROOT/scratch/verify-full-nomaterials.json"; echo "exit=$?"
$HOMEROOT/repository/.venv/bin/python -c 'import json; d = json.load(open("'"$HOMEROOT"'/scratch/verify-full-nomaterials.json")); print("ok:", d["ok"]); [print(c["id"], c["ok"], "" if c["ok"] else json.dumps(c.get("detail", {}))[:400]) for c in d["checks"]]'

mark "6a. generate in the ORIGINAL clone (reference manifest)"
cd "$HOMEROOT/repository"
$LOS validate > "$HOMEROOT/scratch/clone-validate.txt" 2>&1; echo "clone validate exit=$?"; tail -1 "$HOMEROOT/scratch/clone-validate.txt"
$LOS generate > "$HOMEROOT/scratch/clone-generate.txt" 2>&1; echo "clone generate exit=$?"; cat "$HOMEROOT/scratch/clone-generate.txt"

mark "6b. validate and generate IN the restored tree"
cd "$HOMEROOT/scratch/restore-1/repository"
$HOMEROOT/scratch/restore-1/repository/.venv/bin/python -c 'import learning_os; print("learning_os imports from:", learning_os.__file__)'
$HOMEROOT/scratch/restore-1/repository/.venv/bin/python tools/los.py validate > "$HOMEROOT/scratch/restore-validate.txt" 2>&1; echo "restore validate exit=$?"; tail -3 "$HOMEROOT/scratch/restore-validate.txt"
$HOMEROOT/scratch/restore-1/repository/.venv/bin/python tools/los.py generate > "$HOMEROOT/scratch/restore-generate.txt" 2>&1; echo "restore generate exit=$?"; cat "$HOMEROOT/scratch/restore-generate.txt"

mark "6c. compare generated/manifest.json minus timestamps"
$HOMEROOT/repository/.venv/bin/python - <<'EOF'
import json, os
home = os.environ["HOMEROOT"]
a = json.load(open(os.path.join(home, "repository/generated/manifest.json")))
b = json.load(open(os.path.join(home, "scratch/restore-1/repository/generated/manifest.json")))

def strip_ts(node):
    if isinstance(node, dict):
        return {k: strip_ts(v) for k, v in sorted(node.items())
                if k not in ("generated_at", "generated_at_utc", "now", "timestamp")}
    if isinstance(node, list):
        return [strip_ts(v) for v in node]
    return node

sa, sb = json.dumps(strip_ts(a), sort_keys=True, indent=1), json.dumps(strip_ts(b), sort_keys=True, indent=1)
print("equal minus timestamp keys:", sa == sb)
if sa != sb:
    import difflib
    diff = list(difflib.unified_diff(sa.splitlines(), sb.splitlines(), "clone", "restore", lineterm=""))
    print("diff lines:", len(diff))
    print("\n".join(diff[:60]))
print("top-level keys:", sorted(a.keys()))
gen_a, gen_b = a.get("_generated", {}), b.get("_generated", {})
print("_generated clone:", {k: gen_a.get(k) for k in sorted(gen_a)})
print("_generated restore:", {k: gen_b.get(k) for k in sorted(gen_b)})
EOF

mark "DONE"
